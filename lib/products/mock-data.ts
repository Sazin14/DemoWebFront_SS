function completeProduct(product: BaseProduct | Product): Product {
  const category = PRODUCT_CATEGORIES.find((item) => item.name === product.category);
  if (!category) throw new Error(`No category definition found for ${product.category}.`);
  const extraAttributes = "attributes" in product
    ? product.attributes
    : deriveLegacyAttributes(product);
  return {
    ...product,
    sku: ("sku" in product && product.sku) || `DEMO-${product.id.toUpperCase().replace(/[^A-Z0-9]+/g, "-")}`,
    categoryId: ("categoryId" in product && product.categoryId) || category.id,
    attributes: { brand: product.brand, ...extraAttributes },
  };
}

